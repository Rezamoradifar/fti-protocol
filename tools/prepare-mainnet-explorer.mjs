import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(process.cwd()+'/package.json');
const solc=require('solc');
const {Interface,AbiCoder}=require('ethers');
const out=path.resolve(process.argv[2]||'artifacts/mainnet-explorer');
const cfg=JSON.parse(fs.readFileSync(new URL('../deployments/mainnet-20261016.json',import.meta.url)));
const {execFileSync}=require('node:child_process');
if(execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim()!==cfg.sourceRevision)throw Error('Run from the exact deployed source revision');
const sources=Object.fromEntries(fs.readdirSync('contracts').filter(f=>f.endsWith('.sol')).map(f=>[f,{content:fs.readFileSync('contracts/'+f,'utf8')}]));
const settings={optimizer:{enabled:true,runs:200},viaIR:true,evmVersion:'shanghai',outputSelection:{'*':{'*':['abi','evm.bytecode.object','metadata']}}};
const discovered=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources,settings:{outputSelection:{'*':{'*':['abi']}}}}),{import:p=>{const content=fs.readFileSync(path.join('node_modules',p),'utf8');sources[p]={content};return{contents:content}}}));
if(discovered.errors?.some(e=>e.severity==='error'))throw Error('Import compilation failed');
const input={language:'Solidity',sources,settings};
console.log('COMPILING_EXACT_SOURCE');
const output=JSON.parse(solc.compile(JSON.stringify(input)));
if(output.errors?.some(e=>e.severity==='error'))throw Error('Compilation failed');
const models={council:'SevenGuardianCouncil',timelock:'FTITimelock',tokenImplementation:'FTIReserveTokenUpgradeable',token:'FTIProxy',binaryImplementation:'FundedBinaryPlanUpgradeable',binary:'FTIProxy'};
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'standard-input.json'),JSON.stringify(input));
const jobs=[];
for(const [key,name] of Object.entries(models)){
 const artifactBytes=fs.readFileSync('artifacts/'+name+'.json');
 if(require('node:crypto').createHash('sha256').update(artifactBytes).digest('hex')!==cfg.artifactHashes[name])throw Error('Verified artifact hash mismatch: '+name);
 const a=JSON.parse(artifactBytes);
 if(a.bytecode!=='0x'+output.contracts[a.source][name].evm.bytecode.object)throw Error('BYTECODE_MISMATCH '+key);
 const args=AbiCoder.defaultAbiCoder().encode(new Interface(a.abi).deploy.inputs,cfg.constructorArgs[key]).slice(2);
 jobs.push({key,address:cfg[key],contractIdentifier:a.source+':'+name,compilerVersion:solc.version().split('.Emscripten')[0],creationTransactionHash:cfg.transactions[key],constructorArguments:args});
 console.log('BYTECODE_MATCH',key,cfg[key]);
}
fs.writeFileSync(path.join(out,'jobs.json'),JSON.stringify(jobs,null,2));
